const uint8_t* glyph(char c) {
    for (const auto& g : kFont)
        if (g.c == c) return g.cols;
    if (c >= 'a' && c <= 'z') return glyph(static_cast<char>(c - 'a' + 'A'));
    return nullptr;
}

LedSlot led_of(Button b) {
    const auto name = kButtonNames[static_cast<int>(b)];
    for (int i = 0; i < kButtonLeds; ++i)
        if (kButtonLedNames[i] == name) return {1, static_cast<uint8_t>(i)};
    const int i = static_cast<int>(b);
    if (b >= Button::Restart && b <= Button::Shift) return {2, static_cast<uint8_t>(i - static_cast<int>(Button::Restart))};
    if (b >= Button::GroupA && b <= Button::GroupH) return {3, static_cast<uint8_t>(i - static_cast<int>(Button::GroupA))};
    return {0, 0};  // Master encoder push has no LED
}

void build_pad_led_report(const LedState& s, const Map& map, std::array<uint8_t, 49>& out) {
    out.fill(0);
    out[0] = 0x80;
    for (int pad = 0; pad < kPads; ++pad) {  // the report is in hardware id order
        const int hw = map.pad_hw_id[pad];
        if (hw < 0 || hw >= kPads) continue;
        for (int c = 0; c < 3; ++c) out[1 + hw * 3 + c] = clamp_led(s.pad_rgb[pad][c]);
    }
}

void build_group_led_report(const LedState& s, std::array<uint8_t, 57>& out) {
    out[0] = 0x81;
    for (int g = 0; g < 8; ++g)
        for (int lr = 0; lr < 2; ++lr)
            for (int c = 0; c < 3; ++c) out[1 + g * 6 + lr * 3 + c] = clamp_led(s.group_rgb[g][lr][c]);
    for (int t = 0; t < 8; ++t) out[49 + t] = clamp_led(s.transport[t]);
}

void build_button_led_report(const LedState& s, std::array<uint8_t, 32>& out) {
    out[0] = 0x82;
    for (int i = 0; i < kButtonLeds; ++i) out[1 + i] = clamp_led(s.buttons[i]);
}

void build_strip_report(int side, int strip, const uint8_t* screen, std::array<uint8_t, kStripReportSize>& out) {
    out[0] = side == 0 ? 0xE0 : 0xE1;
    const uint8_t header[8] = {0x00, 0x00, static_cast<uint8_t>(strip * 8), 0x00, 0x20, 0x00, 0x08, 0x00};
    std::memcpy(out.data() + 1, header, 8);
    std::memcpy(out.data() + 9, screen + strip * 256, 256);
}

