"""
Make a mixed set of files for the library import (M7 measurement: "100 mixed
clips import during a show without a late frame").

    python tools/make_ingest_test_set.py [--out DIR] [--count 100] [--force]

Default DIR = build/ingest_test (not in git, and outside media/ so the
renderer does not list these files as clips). Needs ffmpeg on PATH (an
external tool). Every picture is generated by ffmpeg's built-in test sources
or written here as SVG, so there is nothing to license. Of every 100 items:

    40 H.264 videos  (24 / 25 / 30 / 50 / 60 fps, 360p .. 1080p, odd sizes)
     6 videos with alpha (PNG-in-MOV, rgba)
     4 clips that already are HAP (copied, not re-encoded)
    20 stills        (PNG with and without alpha, JPG, WebP, BMP)
    10 animated GIFs
    10 SVGs
    10 image sequences (a folder of 20 numbered PNGs each)
"""

import argparse
import os
import random
import shutil
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = ["testsrc2", "mandelbrot", "life=s={s}:mold=10:r={r}:ratio=0.1:death_color=#C83232:life_color=#00ff00",
           "cellauto=s={s}:rule=110:r={r}", "smptehdbars", "rgbtestsrc", "testsrc", "gradients=s={s}:r={r}:speed=0.05"]
SIZES = ["640x360", "1280x720", "854x480", "1366x768", "1920x1080", "720x576", "1024x1024"]
FPS = [24, 25, 30, 50, 60]


def src(i, size, fps, seconds):
    s = SOURCES[i % len(SOURCES)]
    hue = f",hue=h={(i * 37) % 360}"  # every item different, so none is a duplicate of another
    if "{s}" in s:
        return f"{s.format(s=size, r=fps)},trim=duration={seconds}{hue}"
    return f"{s}=size={size}:rate={fps},trim=duration={seconds}{hue}"


def ff(args):
    cmd = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y"] + args
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(" ".join(cmd) + "\n" + r.stderr[-400:])


def svg_text(i, rnd):
    w, h = rnd.choice([(1920, 1080), (800, 800), (400, 120), (1000, 1500)])
    shapes = []
    for k in range(12):
        col = "#%06x" % rnd.randrange(0x1000000)
        x, y, r = rnd.randrange(w), rnd.randrange(h), rnd.randrange(20, max(21, min(w, h) // 3))
        if k % 3 == 0:
            shapes.append(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{col}" opacity="0.8"/>')
        elif k % 3 == 1:
            shapes.append(f'<rect x="{x}" y="{y}" width="{r * 2}" height="{r}" fill="{col}" transform="rotate({k * 13} {x} {y})"/>')
        else:
            shapes.append(f'<polygon points="{x},{y} {x + r},{y + r} {x - r},{y + r}" fill="{col}"/>')
    sized = f'width="{w}" height="{h}" ' if i % 2 else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" {sized}viewBox="0 0 {w} {h}">'
            f'<rect width="{w}" height="{h}" fill="none" stroke="#fff" stroke-width="8"/>' + "".join(shapes) + "</svg>")


def jobs(out, count, rnd):
    scale = count / 100.0
    plan = [("video", 40), ("alpha", 6), ("hap", 4), ("still", 20), ("gif", 10), ("svg", 10), ("seq", 10)]
    n = 0
    for kind, k in plan:
        for j in range(max(1, round(k * scale)) if count >= 10 else (1 if n < count else 0)):
            if n >= count:
                return
            yield kind, n, j
            n += 1


def make(out, kind, n, j, rnd):
    size = SIZES[(n * 3 + j) % len(SIZES)]
    fps = FPS[(n + j) % len(FPS)]
    secs = 3 + (n % 4)
    name = f"{n:03d}_{kind}"
    if kind == "video":
        ff(["-f", "lavfi", "-i", src(n, size, fps, secs), "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
            os.path.join(out, name + ".mp4")])
    elif kind == "alpha":
        ff(["-f", "lavfi", "-i", src(n, "640x360", 25, 3) + ",format=rgba,geq=r='r(X,Y)':g='g(X,Y)':b='b(X,Y)':a='255*X/W'",
            "-c:v", "png", "-pix_fmt", "rgba", os.path.join(out, name + ".mov")])
    elif kind == "hap":
        ff(["-f", "lavfi", "-i", src(n, "1280x720", 30, 3), "-c:v", "hap", "-format", "hap", "-chunks", "4",
            os.path.join(out, name + "_already_hap.mov")])
    elif kind == "still":
        ext = [".png", ".png", ".jpg", ".jpg", ".png", ".webp", ".jpg", ".bmp", ".png", ".jpg"][j % 10]
        vf = src(n, SIZES[j % len(SIZES)], 25, 1)
        extra = ["-frames:v", "1"]
        if ext == ".png" and j % 2 == 0:  # alpha
            vf += ",format=rgba,geq=r='r(X,Y)':g='g(X,Y)':b='b(X,Y)':a='255*Y/H'"
        ff(["-f", "lavfi", "-i", vf] + extra + [os.path.join(out, name + ext)])
    elif kind == "gif":
        ff(["-f", "lavfi", "-i", src(n, "320x180", 12, 2) + ",split[a][b];[a]palettegen[p];[b][p]paletteuse",
            os.path.join(out, name + ".gif")])
    elif kind == "svg":
        with open(os.path.join(out, name + ".svg"), "w", encoding="utf-8") as f:
            f.write(svg_text(n, random.Random(n)))
    elif kind == "seq":
        d = os.path.join(out, name)
        os.makedirs(d, exist_ok=True)
        ext = "png"
        ff(["-f", "lavfi", "-i", src(n, "320x180", 25, 1), "-frames:v", "20", "-start_number", str(1 + j),
            os.path.join(d, f"frame_%04d.{ext}")])
    return name


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "ingest_test"))
    ap.add_argument("--count", type=int, default=100)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if shutil.which("ffmpeg") is None:
        sys.exit("ffmpeg is not on PATH")
    if os.path.isdir(a.out) and os.listdir(a.out):
        if not a.force:
            sys.exit(f"{a.out} is not empty (use --force to recreate it)")
        shutil.rmtree(a.out)
    os.makedirs(a.out, exist_ok=True)
    rnd = random.Random(7)
    todo = list(jobs(a.out, a.count, rnd))
    with ThreadPoolExecutor(max_workers=max(2, (os.cpu_count() or 4) // 2)) as ex:
        names = list(ex.map(lambda t: make(a.out, t[0], t[1], t[2], rnd), todo))
    kinds = {}
    for k, _, _ in todo:
        kinds[k] = kinds.get(k, 0) + 1
    print(f"{len(names)} items in {a.out}: " + ", ".join(f"{v} {k}" for k, v in kinds.items()))


if __name__ == "__main__":
    main()
